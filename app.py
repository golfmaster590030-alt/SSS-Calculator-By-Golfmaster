import numpy_financial as npf

def fwd_super_smart_custom_calculator_with_tax():
    print("=" * 65)
    print(" โปรแกรมคำนวณ FWD Super Smart Savings (รวมลดหย่อนภาษี) ")
    print("=" * 65)

    # 1. รับค่าจากผู้ใช้งาน
    try:
        plan = input("เลือกแผนชำระเบี้ย (พิมพ์ 7 หรือ 15): ").strip()
        if plan not in ["7", "15"]:
            print("กรุณาเลือกแผน 7 หรือ 15 เท่านั้นครับ")
            return

        plan_years = int(plan)
        premium_per_year = float(input("ระบุจำนวนเงินเบี้ยประกันภัยต่อปี (บาท): "))
        tax_bracket = float(input("ระบุอัตราภาษีเงินได้บุคคลธรรมดาของคุณ เช่น 10, 15, 20, 25 (%): "))
        custom_index_rate = float(input("ระบุอัตราผลตอบแทนสมมติจากดัชนีอ้างอิงต่อปี เช่น 4 (หมายถึง 4%): ")) / 100

    except ValueError:
        print("กรุณากรอกตัวเลขให้ถูกต้องด้วยครับ")
        return

    total_protection_years = 25
    total_paid_premium = premium_per_year * plan_years

    # 2. คำนวณสิทธิ์ลดหย่อนภาษี (ลดหย่อนตามเบี้ยจ่ายจริง สูงสุดไม่เกิน 100,000 บาท/ปี)
    eligible_tax_base_per_year = min(premium_per_year, 100000.0)
    tax_saved_per_year = eligible_tax_base_per_year * (tax_bracket / 100.0)
    total_tax_saved = tax_saved_per_year * plan_years
    net_premium_outflow = total_paid_premium - total_tax_saved

    # 3. คำนวณเงินคืนการันตีตามโครงสร้างจริง
    if plan_years == 7:
        total_guaranteed_received = (premium_per_year * 0.01 * 24) + (premium_per_year * 7.00)
        checkpoint_year = 7
        base_checkpoint_bonus = 165848 * (premium_per_year / 150000)
        base_year25_bonus = 874545 * (premium_per_year / 150000)
    else:
        total_guaranteed_received = (premium_per_year * 0.01 * 24) + (premium_per_year * 14.80)
        checkpoint_year = 15
        base_checkpoint_bonus = 420473 * (premium_per_year / 70000)
        base_year25_bonus = 874545 * (premium_per_year / 70000)

    # ปรับสัดส่วนโบนัสดัชนีตามอัตรา % ที่ผู้ใช้กรอกจริง (เทียบกับฐาน 4% หรือ 0.04)
    scale_factor = custom_index_rate / 0.04
    checkpoint_bonus = base_checkpoint_bonus * scale_factor
    year25_bonus = base_year25_bonus * scale_factor
    total_index_bonus = checkpoint_bonus + year25_bonus

    # 4. ผลประโยชน์รวมทั้งหมด
    total_benefits_all = total_guaranteed_received + total_index_bonus
    net_profit = (total_benefits_all + total_tax_saved) - total_paid_premium

    # 5. คำนวณ IRR ตลอด 25 ปี (โดยใช้กระแสเงินสดหลังหักภาษีเงินฝาก/จ่ายสุทธิ)
    cash_flows = [- (premium_per_year - tax_saved_per_year)] * plan_years + [0] * (total_protection_years - plan_years)
    for yr in range(1, total_protection_years + 1):
        if yr <= 24:
            cash_flows[yr - 1] += (premium_per_year * 0.01)
        if yr == 25:
            cash_flows[yr - 1] += (total_guaranteed_received - (premium_per_year * 0.01 * 24))

        if yr == checkpoint_year:
            cash_flows[yr - 1] += checkpoint_bonus
        if yr == total_protection_years:
            cash_flows[yr - 1] += year25_bonus

    try:
        irr_value = npf.irr(cash_flows) * 100
    except:
        irr_value = 0.0

    # 6. แสดงผลลัพธ์
    print("\n" + "=" * 65)
    print(f" ผลสรุปการคำนวณแผน 25/{plan_years} (รวมลดหย่อนภาษี & ดัชนี {custom_index_rate*100:.2f}%) ")
    print("=" * 65)
    print(f"** รวมเบี้ยประกันภัยที่จ่ายตลอดสัญญา : {total_paid_premium:,.2f} บาท")
    print(f"** สิทธิประโยชน์จากการลดหย่อนภาษีรวม : {total_tax_saved:,.2f} บาท (ฐานภาษี {tax_bracket}%)")
    print(f"** ต้นทุนเบี้ยประกันสุทธิหลังหักภาษี : {net_premium_outflow:,.2f} บาท")
    print(f"-" * 65)
    print(f"** รวมเงินคืนการันตีที่ได้รับ : {total_guaranteed_received:,.2f} บาท")
    print(f"ผลประโยชน์ที่ไม่การันตี (Index Linked):")
    print(f" - รับโบนัสงวดที่ 1 (ปีที่ {checkpoint_year}) : {checkpoint_bonus:,.2f} บาท")
    print(f" - รับโบนัสงวดที่ 2 (ปีที่ 25) : {year25_bonus:,.2f} บาท")
    print(f" - รวมผลประโยชน์ไม่การันตีทั้งหมด : {total_index_bonus:,.2f} บาท")
    print(f"-" * 65)
    print(f"** รวมผลประโยชน์ทั้งหมด (การันตี + ไม่การันตี) : {total_benefits_all:,.2f} บาท")
    print(f"** กำไรสุทธิรวมส่วนลดหย่อนภาษี : {net_profit:,.2f} บาท")
    print(f"** อัตราผลตอบแทนเฉลี่ยต่อปี (IRR) : {irr_value:.2f}% ต่อปี")
    print("=" * 65)

# เรียกใช้งานโปรแกรม
fwd_super_smart_custom_calculator_with_tax()
